//! Language tables of Maya2's text normaliser, generated from upstream's source text
//! (`maya3/text/tn/indic_languages.py`, `tn/normalize.py`, `tn/assamese_numbers.py`, `rules.py`,
//! `lexicon.py` at MayaResearch/maya2-native `bbfdb152`, vendored `tn` commit `fe5e6ec`, Apache-2.0;
//! the Assamese number words are AI4Bharat indic-numtowords data, MIT) by parsing the Python AST
//! (`ast.literal_eval`), never by importing it. Treat it as data: a fix belongs upstream's tables.
//!
//! Each `LangData` is a class's attributes after Python's inheritance (Assamese extends Bengali,
//! the others `LangBase`); dictionaries keep Python's insertion order. English's `ONES`, `LETTERS`
//! and `ORDINAL_EXCEPTIONS` are computed upstream and built in `lang.rs`.
/// One language class's literal attributes.
pub(super) struct LangData {
    pub code: &'static str,
    pub ones: &'static [&'static str],
    pub hundred: &'static str,
    pub thousand: &'static str,
    pub lakh: &'static str,
    pub crore: &'static str,
    pub letters: &'static [(&'static str, &'static str)],
    pub months: &'static [&'static str],
    pub month_aliases: &'static [(&'static str, u32)],
    pub sym: &'static [(&'static str, &'static str)],
    pub time_on_hour: &'static str,
    pub time_hm: &'static str,
    pub range: &'static str,
    pub range_to: &'static str,
    pub ratio: &'static str,
    pub power: &'static str,
    pub fraction: &'static str,
    pub decade_short: &'static str,
    pub decade_full: &'static str,
    pub periods: &'static [(&'static str, &'static str)],
    pub time_markers: &'static [&'static str],
    pub marker_suffixes: &'static [(&'static str, &'static str)],
    pub period_detect: &'static [(&'static str, &'static str)],
    pub year_words: &'static [&'static str],
    pub id_keywords: &'static [&'static str],
    pub id_after_words: &'static [&'static str],
    pub label_words: &'static [&'static str],
    pub minute_words: &'static [&'static str],
    pub scale_words: &'static [(&'static str, &'static str)],
    pub currency_words: &'static [(&'static str, &'static str)],
    pub ordinal_exceptions: &'static [(u32, &'static str)],
    pub ordinal_suffix: &'static str,
    pub ordinal_input_suffixes: &'static [&'static str],
    pub unit_words: &'static [(&'static str, &'static str)],
    pub abbrev_units: &'static [(&'static str, &'static str)],
    pub number_word: &'static str,
    pub ampm_words: &'static [(&'static str, &'static str)],
    pub count_one: Option<&'static str>,
    pub singular_nouns: &'static [(&'static str, &'static str)],
}

